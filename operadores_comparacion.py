#  operaciones de comparación

print(1== 4) # si es igual = True

print(2 != 3) # si es diferente = True

print(5 > 3) # si es mayor = True

print(5 < 3) # si es menor = True

print(5 >= 3) # si es mayor o igual = True

print(5 <= 3) # si es menor o igual = True


print(2== 5) # si es igual = false

print(3 != 3) # si es diferente = false

print(4 > 3) # si es mayor = false 

print(3 < 2) # si es menor = false 

print(5 >= 3) # si es mayor o igual = falase

print(5 <= 3) # si es menor o igual = false
